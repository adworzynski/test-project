import path from 'node:path';
import { exists, listDir, writeText } from '../util/fs.js';
import { slugify, today } from '../util/text.js';
import { KeelError } from '../util/errors.js';
import type { Project } from '../project.js';

export interface ExportResult {
  dir: string;
  files: string[];
  /** Spec Kit's commands need its .specify/ scripts (`specify init --here`). */
  specifyMissing: boolean;
}

/**
 * `keel export speckit <id>` (MG-3): writes a Feature change or story as a Spec Kit feature folder
 * (spec.md, plan.md, tasks.md) so `/speckit.implement` can run on it during a migration.
 */
export function exportSpecKit(project: Project, id: string, outDir = 'specs'): ExportResult {
  const g = project.graph;
  const n = g.get(id.toUpperCase());
  if (!n || (n.type !== 'change' && n.type !== 'story')) throw new KeelError(`${id} is not a story or change.`);
  const specsAbs = path.join(project.root, outDir);
  const nums = listDir(specsAbs)
    .map((d) => Number(d.match(/^(\d{3})-/)?.[1] ?? 0))
    .filter(Boolean);
  const existing = listDir(specsAbs).find((d) => d.endsWith(`-${slugify(n.title)}`) || d.includes(n.id.toLowerCase()));
  const folder = existing ?? `${String((nums.length ? Math.max(...nums) : 0) + 1).padStart(3, '0')}-${slugify(n.title)}`;
  const dir = path.join(specsAbs, folder);
  const crit = g.criteriaOf(n.id);
  const reqs = g.requirementsOf(n.id);
  const why = n.body.match(/##\s+Why\s*\n([\s\S]*?)(?=\n##\s|$)/)?.[1]?.replace(/<!--[\s\S]*?-->/g, '').trim();
  const narrative = n.type === 'story' ? n.body.replace(/^#.*\n/, '').split(/\n##\s/)[0]!.trim() : why ?? n.title;
  const scen = crit.map((c, i) => {
    const gv = (c.given ?? []).join(' and ') || 'the app is in its usual state';
    const w = (c.when ?? []).join(' and ') || '…';
    const t = (c.then ?? []).join(' and ') || c.title;
    return `${i + 1}. **Given** ${gv}, **When** ${w}, **Then** ${t} <!-- Keel ${c.id} -->`;
  });
  const frLines = reqs.map((r, i) => {
    const text = r.body.split('\n').slice(1).join(' ').replace(/_.*?_/g, '').trim() || r.title;
    return `- **FR-${String(i + 1).padStart(3, '0')}**: ${text} <!-- Keel ${r.id} -->`;
  });
  const spec = [
    `# Feature Specification: ${n.title}`,
    '',
    `**Feature Branch**: \`${folder}\`  `,
    `**Created**: ${today()}  `,
    `**Status**: ${n.status === 'draft' ? 'Draft' : 'Approved'}  `,
    `**Input**: Keel ${n.id} (\`${n.file}\`)`,
    '',
    '## User Scenarios & Testing *(mandatory)*',
    '',
    `### User Story 1 - ${n.title} (Priority: P1)`,
    '',
    narrative,
    '',
    '**Acceptance Scenarios**:',
    '',
    ...(scen.length ? scen : ['1. _No criteria yet; add them in Keel first._']),
    '',
    '## Requirements *(mandatory)*',
    '',
    '### Functional Requirements',
    '',
    ...(frLines.length ? frLines : ['- _No linked requirements._']),
    '',
  ].join('\n');
  const adrs = (n.links.adr ?? []).map((a) => g.get(a)).filter(Boolean);
  const design = n.body.match(/##\s+Design\s*\n([\s\S]*?)(?=\n##\s|$)/)?.[1]?.replace(/<!--[\s\S]*?-->/g, '').trim();
  const plan = [
    `# Implementation Plan: ${n.title}`,
    '',
    `**Branch**: \`${folder}\` | **Date**: ${today()} | **Spec**: [spec.md](./spec.md)`,
    '',
    '## Summary',
    '',
    design || narrative,
    '',
    '## Technical Context',
    '',
    `**Project Type**: ${project.config.stack} (${project.config.profile})  `,
    `**Testing**: tag every test with its Keel criterion, e.g. \`// @keel ${crit[0]?.id ?? 'AC-001'}\`; Keel checks coverage with \`keel verify\`.`,
    '',
    ...(adrs.length ? ['## Decisions (Keel ADRs)', '', ...adrs.map((a) => `- ${a!.id}: ${a!.title} (${a!.status})`), ''] : []),
  ].join('\n');
  let t = 0;
  const tid = () => `T${String(++t).padStart(3, '0')}`;
  const keelTasks = g.files.get(n.file)?.checkboxes ?? [];
  const tasks = [
    `# Tasks: ${n.title}`,
    '',
    '**Input**: spec.md, plan.md. Generated by `keel export speckit`; Keel stays the source of truth.',
    '',
    '## Phase 1: Tests first (User Story 1)',
    '',
    ...crit.map((c) => `- [ ] ${tid()} [US1] Write a failing test for ${c.id} "${c.title}", tagged \`@keel ${c.id}\``),
    '',
    '## Phase 2: Implementation (User Story 1)',
    '',
    ...(keelTasks.length ? keelTasks.map((k) => `- [${k.checked ? 'X' : ' '}] ${tid()} [US1] ${k.text}`) : [`- [ ] ${tid()} [US1] Implement until the tests pass`]),
    '',
    '## Phase 3: Verify',
    '',
    `- [ ] ${tid()} Run \`keel verify --run --record\`, then \`keel done ${n.id}\``,
    '',
  ].join('\n');
  const files = [
    ['spec.md', spec],
    ['plan.md', plan],
    ['tasks.md', tasks],
  ] as const;
  for (const [f, text] of files) writeText(path.join(dir, f), text);
  return {
    dir: path.relative(project.root, dir).split(path.sep).join('/'),
    files: files.map(([f]) => f),
    specifyMissing: !exists(path.join(project.root, '.specify')),
  };
}
