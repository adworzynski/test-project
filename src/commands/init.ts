export function detectStack(root: string): Stack | undefined {
  if (exists(path.join(root, 'pubspec.yaml'))) return 'flutter';
  const pkg = readTextIf(path.join(root, 'package.json'));
  if (pkg) {
    try {
      const js = JSON.parse(pkg) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
      const deps = { ...js.dependencies, ...js.devDependencies };
      if (deps.expo || deps['react-native']) return 'expo';
    } catch {
      // fall through to web
    }
    return 'web';
  }
  if (exists(path.join(root, 'Package.swift')) || listDir(root).some((f) => f.endsWith('.xcodeproj') || f.endsWith('.xcworkspace'))) return 'swiftui';
  if (['build.gradle', 'build.gradle.kts', 'settings.gradle', 'settings.gradle.kts'].some((f) => exists(path.join(root, f)))) return 'compose';
  return undefined;
}

export function detectAgents(root: string): AgentId[] {
  const found: AgentId[] = [];
  const has = (p: string) => exists(path.join(root, p));
  if (has('.claude') || has('CLAUDE.md')) found.push('claude');
  if (has('.github/copilot-instructions.md') || has('.github/agents') || has('.github/instructions') || has('.vscode')) found.push('copilot');
  if (has('.cursor') || has('.cursorrules')) found.push('cursor');
  if (has('.codex') || has('AGENTS.md')) found.push('codex');
  return found;
}

export function detectProjectName(root: string): string {
  const pubspec = readTextIf(path.join(root, 'pubspec.yaml'));
  if (pubspec) {
    const m = pubspec.match(/^name:\s*([\w-]+)/m);
    if (m) return m[1]!;
  }
  const pkg = readTextIf(path.join(root, 'package.json'));
  if (pkg) {
    try {
      const n = (JSON.parse(pkg) as { name?: string }).name;
      if (n) return n.replace(/^@[^/]+\//, '');
    } catch {
      // ignore
    }
  }
  return path.basename(path.resolve(root));
}

/** Copies a pack folder into the project and keeps a pristine copy in .keel/.pack for `keel upgrade`. */
function installPackDir(paths: ProjectPaths, sub: string, dest: string, written: string[]) {
  const src = path.join(PACK_DIR, sub);
  for (const rel of walk(src, src, { ignoreDirs: new Set() })) {
    const text = readText(path.join(src, rel));
    const target = path.join(dest, rel);
    if (!exists(target)) {
      writeText(target, text);
      written.push(path.relative(paths.root, target).split(path.sep).join('/'));
    }
    writeText(path.join(paths.pack, sub, rel), text);
  }
}

