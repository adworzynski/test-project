export function ciWorkflow(stack: Stack): string {
  const s = CI_STEPS[stack];
  return [
    '# Generated by keel init. Runs the tests, then Keel checks criteria coverage, drift and new',
    '# dependencies, and posts a summary on the pull request (VG-4). Adjust the test step freely.',
    'name: keel',
    'on:',
    '  pull_request:',
    '  push:',
    '    branches: [main]',
    'permissions:',
    '  contents: read',
    '  pull-requests: write',
    'jobs:',
    '  verify:',
    `    runs-on: ${s.runsOn}`,
    '    steps:',
    '      - uses: actions/checkout@v4',
    '        with:',
    '          fetch-depth: 0',
    ...s.setup,
    '      - name: Tests',
    '        id: tests',
    '        continue-on-error: true',
    `        run: mkdir -p .keel/tmp && ${s.test}`,
    `      - uses: ${ACTION_REF}`,
    '        with:',
    `          results: ${s.results}`,
    '      - name: Fail if tests failed',
    "        if: steps.tests.outcome == 'failure'",
    '        run: exit 1',
    '',
  ].join('\n');
}

export interface InitOptions {
  stack?: Stack;
  profile?: Profile;
  agents?: AgentId[];
  project?: string;
  force?: boolean;
  ci?: boolean;
}

export interface InitResult {
  root: string;
  config: KeelConfig;
  detected: { stack?: Stack; agents: AgentId[] };
  created: string[];
  compile: CompileResult;
}

/** `keel init` (J1 step 1): detect the stack and agents, write .keel/ and the agent files. */
export function initProject(root: string, opts: InitOptions = {}): InitResult {
  const paths = new ProjectPaths(root);
  if (exists(paths.config) && !opts.force) throw new KeelError('This project already has .keel/keel.yaml. Run `keel compile` to refresh agent files, or `keel init --force` to rewrite the config.');
  const detectedStack = detectStack(root);
  const stack = opts.stack ?? detectedStack;
  if (!stack) throw new KeelError(`Couldn't detect the stack. Pass --stack (${STACKS.join(', ')}).`);
  const detectedAgents = detectAgents(root);
  const agents = opts.agents?.length ? opts.agents : detectedAgents.length ? detectedAgents : [...ALL_AGENTS];
  const config = defaultConfig({ project: opts.project ?? detectProjectName(root), stack, profile: opts.profile, agents, owner: currentUser(root) });
  config.initialized = nowIso();
  config.pack.version = (YAML.parse(readText(path.join(PACK_DIR, 'pack.yaml'))) as { version: string }).version ?? pkgVersion();
  const created: string[] = [];
  writeText(paths.config, stringifyConfig(config));
  created.push('.keel/keel.yaml');
  installPackDir(paths, 'workflows', paths.workflows, created);
  installPackDir(paths, 'templates', paths.templates, created);
  installPackDir(paths, 'agents', paths.agents, created);
  installPackDir(paths, 'skills', path.join(paths.agents, 'skills'), created);
  writeText(path.join(paths.pack, 'pack.yaml'), readText(path.join(PACK_DIR, 'pack.yaml')));
  ensureMemoryFiles(paths);
  created.push('.keel/memory/decisions.md', '.keel/memory/constraints.md');
  writeText(path.join(paths.keel, '.gitignore'), '# Derived or scratch files\nindex.sqlite\ntmp/\n');
  writeText(
    path.join(paths.artifacts, 'README.md'),
    '# Keel artifacts\n\nOne Markdown file per artifact, with YAML front-matter (id, type, status, links, owner, created, updated).\n' +
      'Sections whose heading starts with an ID (`### FR-001: …`, `### AC-001: …`, `### SC-001: …`) are artifacts too.\n\n' +
      '| Folder | Holds |\n| --- | --- |\n| brief/ | one-page brief (BR) |\n| prd/ | PRD with FR/NFR requirements (PRD) |\n' +
      '| screens/ | screen map with SC screens (SM) |\n| tokens/ | design tokens (DT) |\n| adr/ | decision records (ADR) |\n' +
      '| stories/ | stories with AC criteria (ST) |\n| changes/ | Quick and Feature changes with deltas (CH); merged ones in changes/archive/ |\n' +
      '| release/ | release checklists (RL) |\n| sources/ | imported source documents (SRC) |\n',
  );
  for (const d of ['brief', 'prd', 'screens', 'tokens', 'adr', 'stories', 'changes', 'release']) fs.mkdirSync(paths.artifactDir(d), { recursive: true });
  const project = new Project(root);
  generateSpec(project);
  if (opts.ci !== false) {
    const wf = path.join(root, '.github', 'workflows', 'keel.yml');
    if (!exists(wf)) {
      writeText(wf, ciWorkflow(stack));
      created.push('.github/workflows/keel.yml');
    }
  }
  const compile = compileAgents(project, agents);
  return { root, config, detected: { stack: detectedStack, agents: detectedAgents }, created, compile };
}
