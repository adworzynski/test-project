import path from 'node:path';
import { exists, listDir, readTextIf, writeText } from '../util/fs.js';
import { PACK_DIR } from '../paths.js';
import type { AgentId } from '../config.js';
import type { Project } from '../project.js';

export const BEGIN = '<!-- keel:begin · generated by `keel compile` from .keel/agents/ · edit the source, not this block -->';
export const END = '<!-- keel:end -->';

/** Size limits per output (NF-4). Bytes for Codex (it truncates AGENTS.md at 32 KiB), lines elsewhere. */
export const LIMITS = {
  'AGENTS.md': { bytes: 32 * 1024 },
  'CLAUDE.md': { lines: 200 },
  '.github/copilot-instructions.md': { bytes: 8 * 1024 },
  '.cursor/rules/keel.mdc': { lines: 500 },
} as const;

export interface CompileResult {
  written: string[];
  unchanged: string[];
  warnings: string[];
}

/** Replaces Keel's managed block in a file, keeping everything the user wrote around it. */
export function upsertBlock(existing: string | undefined, block: string): string {
  const wrapped = `${BEGIN}\n${block.trim()}\n${END}`;
  if (!existing || !existing.trim()) return wrapped + '\n';
  const b = existing.indexOf(BEGIN.slice(0, 20));
  const e = existing.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) return existing.slice(0, b) + wrapped + existing.slice(e + END.length);
  return existing.replace(/\s*$/, '\n\n') + wrapped + '\n';
}

function source(project: Project, rel: string): string | undefined {
  return readTextIf(path.join(project.paths.agents, rel)) ?? readTextIf(path.join(PACK_DIR, 'agents', rel));
}

/** Skill names available: project copies in .keel/agents/skills override the bundled pack. */
export function skillNames(project: Project): string[] {
  const names = new Set<string>([...listDir(path.join(project.paths.agents, 'skills')), ...listDir(path.join(PACK_DIR, 'skills'))]);
  return [...names].filter((n) => /^[a-z0-9-]+$/.test(n)).sort();
}

export function skillText(project: Project, name: string): string | undefined {
  return readTextIf(path.join(project.paths.agents, 'skills', name, 'SKILL.md')) ?? readTextIf(path.join(PACK_DIR, 'skills', name, 'SKILL.md'));
}

/** Extracts one "## Heading" section from Markdown. */
function section(md: string, heading: string): string {
  const lines = md.split('\n');
  const i = lines.findIndex((l) => l.trim().toLowerCase() === `## ${heading}`.toLowerCase());
  if (i === -1) return '';
  const j = lines.findIndex((l, k) => k > i && /^##\s/.test(l));
  return lines.slice(i, j === -1 ? undefined : j).join('\n').trim();
}

export function agentsMd(project: Project): string {
  const instructions = source(project, 'instructions.md') ?? '';
  const constitution = source(project, 'constitution.md');
  const parts = [instructions.trim()];
  if (constitution?.trim()) parts.push(constitution.trim().replace(/^# /m, '## '));
  return parts.join('\n\n');
}

function claudeMd(): string {
  return [
    '@AGENTS.md',
    '',
    '## Claude Code and Keel',
    '- A SessionStart hook (`.claude/settings.json`) runs `keel context --session`, so the current story,',
    '  open criteria, decisions and constraints are in context after startup, `/clear` and compaction.',
    '- A Stop hook records token use in the local ledger (`keel cost`). Nothing leaves this machine.',
    '- Keel skills are slash commands: `/keel-next`, `/keel-implement`, `/keel-change`, and the rest.',
    '- The `keel` MCP server (`.mcp.json`) exposes get_status, next_steps, get_context, submit_artifact,',
    '  request_review, record_evidence, record_decision and report_cost.',
  ].join('\n');
}

function copilotMd(project: Project): string {
  const rules = section(source(project, 'instructions.md') ?? '', 'Rules');
  return [
    '# Keel workflow',
    '',
    'This repository is managed with Keel. Full guidance is in `AGENTS.md`. Start each session by calling',
    'the Keel MCP tool `get_context` (or run `keel context --session`), and use `next_steps` when unsure.',
    '',
    rules,
  ].join('\n');
}

function cursorMdc(project: Project): string {
  const rules = section(source(project, 'instructions.md') ?? '', 'Rules');
  return [
    '---',
    'description: Keel workflow rules (generated by keel compile; edit .keel/agents/ instead)',
    'alwaysApply: true',
    '---',
    '',
    '# Keel workflow',
    '',
    'Full guidance is in `AGENTS.md`. Start each session by calling the Keel MCP tool `get_context`',
    '(or `keel context --session`) and use `next_steps` when unsure what to do.',
    '',
    rules,
    '',
  ].join('\n');
}

function mergeJson(file: string, mutate: (obj: Record<string, unknown>) => void): string {
  let obj: Record<string, unknown> = {};
  const prev = readTextIf(file);
  if (prev?.trim()) {
    try {
      obj = JSON.parse(prev);
    } catch {
      throw new Error(`${file} is not valid JSON; fix it or remove it, then run keel compile again`);
    }
  }
  mutate(obj);
  return JSON.stringify(obj, null, 2) + '\n';
}

function upsertToml(existing: string | undefined, table: string, body: string): string {
  const block = `[${table}]\n${body.trim()}\n`;
  if (!existing?.trim()) return block;
  const re = new RegExp(`\\[${table.replace(/\./g, '\\.')}\\]\\n(?:(?!\\[)[^\\n]*\\n?)*`, 'm');
  if (re.test(existing)) return existing.replace(re, block + '\n').replace(/\n{3,}/g, '\n\n');
  return existing.replace(/\s*$/, '\n\n') + block;
}

const SKILL_DIRS: Record<AgentId, string[]> = {
  claude: ['.claude/skills'],
  copilot: ['.github/skills', '.agents/skills'],
  cursor: ['.agents/skills'],
  codex: ['.agents/skills'],
};

/** Hooks Keel installs in Claude Code: session-start re-injection (AE-5) and cost capture (RC-3). */
const CLAUDE_HOOKS = {
  SessionStart: 'keel context --session --hook claude',
  Stop: 'keel cost hook claude',
};

/**
 * `keel compile` (AE-1, AE-2): one instruction source in .keel/agents/ becomes each agent's native
 * files, plus skills, MCP server registration and hooks. Idempotent: no timestamps, stable order.
 */
export function compileAgents(project: Project, agents: AgentId[] = project.config.agents): CompileResult {
  const res: CompileResult = { written: [], unchanged: [], warnings: [] };
  const write = (rel: string, content: string) => {
    const changed = writeText(path.join(project.root, rel), content);
    (changed ? res.written : res.unchanged).push(rel);
  };
  const root = (rel: string) => path.join(project.root, rel);
  const mcp = { command: project.config.mcp.command, args: project.config.mcp.args };

  // AGENTS.md is read by Codex, Copilot and Cursor, and imported by CLAUDE.md, so it is always written.
  write('AGENTS.md', upsertBlock(readTextIf(root('AGENTS.md')), agentsMd(project)));
  if (agents.includes('claude')) {
    write('CLAUDE.md', upsertBlock(readTextIf(root('CLAUDE.md')), claudeMd()));
    write(
      '.mcp.json',
      mergeJson(root('.mcp.json'), (o) => {
        const servers = (o.mcpServers ??= {}) as Record<string, unknown>;
        servers.keel = { type: 'stdio', ...mcp };
      }),
    );
    write(
      '.claude/settings.json',
      mergeJson(root('.claude/settings.json'), (o) => {
        const hooks = (o.hooks ??= {}) as Record<string, { matcher?: string; hooks: { type: string; command: string }[] }[]>;
        for (const [event, command] of Object.entries(CLAUDE_HOOKS)) {
          const list = (hooks[event] ??= []);
          const others = list.filter((g) => !g.hooks?.some((h) => h.command?.startsWith('keel ')));
          hooks[event] = [...others, { hooks: [{ type: 'command', command }] }];
        }
      }),
    );
  }
  if (agents.includes('copilot')) {
    write('.github/copilot-instructions.md', upsertBlock(readTextIf(root('.github/copilot-instructions.md')), copilotMd(project)));
    write(
      '.vscode/mcp.json',
      mergeJson(root('.vscode/mcp.json'), (o) => {
        const servers = (o.servers ??= {}) as Record<string, unknown>;
        servers.keel = { type: 'stdio', ...mcp };
      }),
    );
  }
  if (agents.includes('cursor')) {
    write('.cursor/rules/keel.mdc', cursorMdc(project));
    write(
      '.cursor/mcp.json',
      mergeJson(root('.cursor/mcp.json'), (o) => {
        const servers = (o.mcpServers ??= {}) as Record<string, unknown>;
        servers.keel = mcp;
      }),
    );
  }
  if (agents.includes('codex')) {
    const toml = `command = ${JSON.stringify(mcp.command)}\nargs = [${mcp.args.map((a) => JSON.stringify(a)).join(', ')}]`;
    write('.codex/config.toml', upsertToml(readTextIf(root('.codex/config.toml')), 'mcp_servers.keel', toml));
  }

  const dirs = [...new Set(agents.flatMap((a) => SKILL_DIRS[a]))].sort();
  for (const name of skillNames(project)) {
    const text = skillText(project, name);
    if (!text) continue;
    if (!/^---\nname:\s*\S+\ndescription:\s*\S/m.test(text)) res.warnings.push(`skill ${name} lacks name/description front-matter`);
    for (const d of dirs) write(`${d}/${name}/SKILL.md`, text);
  }

  for (const [rel, lim] of Object.entries(LIMITS)) {
    const text = readTextIf(root(rel));
    if (text === undefined) continue;
    if ('bytes' in lim && Buffer.byteLength(text) > lim.bytes)
      res.warnings.push(`${rel} is ${Buffer.byteLength(text)} bytes, over the ${lim.bytes}-byte limit; the agent may truncate it silently. Trim .keel/agents/.`);
    if ('lines' in lim && text.split('\n').length > lim.lines)
      res.warnings.push(`${rel} is ${text.split('\n').length} lines, over the ${lim.lines}-line guideline. Trim .keel/agents/.`);
  }
  if (!exists(root('AGENTS.md'))) res.warnings.push('AGENTS.md was not written');
  return res;
}
